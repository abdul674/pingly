  def platform_name(platform)
    case platform
    when "slack" then "Slack"
    when "gmail" then "Gmail"
    else platform&.capitalize || "Platform"
    end
  end

  def status_badge(status)
    classes = case status
    when "unread" then "bg-blue-100 text-blue-800"
    when "read" then "bg-gray-100 text-gray-600"
    when "done" then "bg-green-100 text-green-800"
    when "snoozed" then "bg-amber-100 text-amber-800"
    else "bg-gray-100 text-gray-600"
    end

    tag.span(status.capitalize, class: "inline-flex items-center rounded-full px-2 py-0.5 text-xs font-medium #{classes}")
  end

  def time_ago_short(time)
    return "" if time.nil?
    time_ago_in_words(time) + " ago"
  end
